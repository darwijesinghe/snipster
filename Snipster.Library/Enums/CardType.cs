namespace Snipster.Library.Enums
{
    /// <summary>
    /// Defines the various types of credit cards that can be identified based on their number patterns.
    /// </summary>
    public enum CardType
    {
        /// <summary>
        /// Represents an unknown or unsupported card type.
        /// </summary>
        Unknown,
        /// <summary>
        /// Represents a Visa card.
        /// </summary>
        Visa,
        /// <summary>
        /// Represents a MasterCard card.
        /// </summary>
        MasterCard,
        /// <summary>
        /// Represents an American Express card.
        /// </summary>
        AmericanExpress,
        /// <summary>
        /// Represents a Discover card.
        /// </summary>
        Discover,
        /// <summary>
        /// Represents a JCB card.
        /// </summary>
        JCB,
        /// <summary>
        /// Represents a Diners Club card.
        /// </summary>
        DinersClub
    }
}
